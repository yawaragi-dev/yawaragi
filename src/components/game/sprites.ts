/**
 * Pixel-art sprites with a tiny palette per sprite.
 *
 * Each pixel row is a string of single chars:
 *  - '.' = transparent
 *  - any other char = look up in the sprite's `palette` for the fill colour.
 *
 * Conventions per sprite are documented at each definition. Keeping the
 * encoding short means a 14×22 sprite is 22 short strings — easy to read
 * and tweak.
 */

export interface Sprite {
  pixels: string[]
  palette: Record<string, string>
}

